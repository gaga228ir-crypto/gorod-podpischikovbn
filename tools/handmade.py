class H:
    def __init__(self, name, lights="warm"):
        self.r = {"shape": "custom", "name": name, "lights": lights, "parts": []}

    def p(self, t, x, y, z, w, h, d, c, g=0.0, win=False, r=0.0):
        self.r["parts"].append({"t": t, "p": [round(x, 3), round(y, 3), round(z, 3)], "s": [round(w, 3), round(h, 3), round(d, 3)],
                                "c": c, "g": g, "r": r, "w": win})
        return y + h


