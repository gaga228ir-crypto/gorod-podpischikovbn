def obsidian_cliff():
    """#6 @tailerderden26: дом на краю отвесного утёса, фасад из тёмного полированного обсидиана и изогнутых линз,
    отражает небо — издалека будто растворяется в воздухе."""
    h = H("Обсидиановый призрак", "cool")
    rock, rock2, obs = "#4b4658", "#5d5870", "#17121f"
    # утёс: каменный массив сзади, отвесный край спереди, уступы
    h.p("box", 0, 0, -.18, .96, .5, .6, rock)
    h.p("box", -.3, 0, .2, .34, .32, .2, rock2)
    h.p("box", .32, 0, .16, .3, .22, .24, rock2)
    h.p("box", -.12, .5, -.32, .5, .08, .3, rock2)
    h.p("box", .35, .5, -.35, .26, .14, .26, rock)
    # лес на утёсе и у подножия
    for x, z, s in ((-.4, -.38, .22), (-.3, -.42, .18), (.4, -.1, .18), (-.42, .4, .2), (.42, .42, .18), (.12, .45, .16)):
        y = .5 if z < 0 else 0
        h.p("cone", x, y, z, s * .7, s * 1.6, s * .7, "#1f7a4a", .05)
    # дом: обсидиановый корпус, нависающий над краем
    h.p("box", .02, .5, .06, .56, .3, .44, obs, .12)
    h.p("box", .06, .8, .0, .4, .2, .32, obs, .12, r=18)
    # изогнутые линзы — отражают небо
    for x, y in ((-.15, .6), (.05, .6), (.22, .6), (-.05, .72), (.15, .72)):
        h.p("sphere", x, y, .275, .16, .1, .04, "#8fc4ff", .55)
    h.p("sphere", .27, .86, .1, .05, .1, .14, "#8fc4ff", .55)
    h.p("dome", .06, 1.0, .0, .3, .16, .24, "#6f9be8", .45)
    # тонкая неоновая кромка и консоль-терраса над пропастью
    h.p("box", .02, .795, .06, .58, .012, .46, "#b48cff", 1)
    h.p("box", .02, .49, .33, .5, .02, .14, "#2a2238")
    h.p("box", .02, .51, .4, .5, .05, .005, "#8fc4ff", .5)
    # облака вокруг — «растворяется в воздухе»
    for x, y, z, s in ((-.4, 1.05, .25, .3), (.42, 1.2, -.2, .26), (-.25, 1.35, -.3, .22)):
        h.p("sphere", x, y, z, s, s * .4, s * .6, "#e6ecff", .35)
    return h.r


def spider_tower():
    """#9 @1makse: очень высокий красно-синий небоскрёб, по которому взбирается человек-паук (паутина по фасаду)."""
    h = H("Небоскрёб Паука", "cool")
    red, blue, white = "#d81f2a", "#1f4fd8", "#f2f4ff"
    y = h.p("box", 0, 0, 0, .52, .6, .52, blue, .05, win=True)
    y = h.p("box", 0, y, 0, .54, .03, .54, white, .8)
    y = h.p("box", 0, y, 0, .44, .6, .44, red, .05, win=True)
    y = h.p("box", 0, y, 0, .46, .03, .46, white, .8)
    y = h.p("box", 0, y, 0, .34, .38, .34, blue, .05, win=True)
    y = h.p("pyramid", 0, y, 0, .36, .14, .36, red)
    y = h.p("cyl", 0, y, 0, .025, .32, .025, "#c0c6d4")
    h.p("sphere", 0, y - .02, 0, .05, .05, .05, "#ff3b3b", 1)
    # паутина на фасаде: «лучи» и «круги» белыми нитями
    for x in (-.12, 0, .12):
        h.p("box", x, .62, .224, .008, .58, .006, white, .4)
    for yy in (.75, .9, 1.05):
        h.p("box", 0, yy, .224, .3, .008, .006, white, .4)
    # нить от героя к крыше
    h.p("box", .06, 1.05, .225, .006, .55, .006, white, .6)
    # герой в красно-синем костюме карабкается по стене (крупно, чтобы было видно в городе)
    hz, k, cx, cy = .25, 1.6, .06, .86
    P = lambda t, x, y, w, hh, d, c, g=0.0, dz=0.0: h.p(t, cx + x * k, cy + y * k, hz + dz, w * k, hh * k, d * k, c, g)
    P("sphere", 0, .14, .06, .07, .05, red)                    # голова
    P("sphere", -.015, .165, .018, .022, .008, white, .9, .025)  # глаза
    P("sphere", .015, .165, .018, .022, .008, white, .9, .025)
    P("box", 0, .04, .07, .1, .04, red)                         # торс
    P("box", 0, .07, .03, .03, .005, "#111111", 0, .022)       # эмблема
    P("box", -.045, .1, .02, .1, .03, red)                      # руки вверх
    P("box", .045, .07, .02, .09, .03, red)
    P("box", -.02, -.05, .025, .09, .03, blue)                  # ноги
    P("box", .025, -.07, .025, .09, .03, blue)
    return h.r


