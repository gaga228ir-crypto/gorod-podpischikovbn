"""Дома, собранные вручную (Claude) для заказов «по описанию», с которыми не справилась нейросеть.
python tools/handmade.py → handmade.json в корне сайта: {"номер заказа": рецепт}. Бот берёт его вместо нейросети (/ai_hand N)."""
import json
from pathlib import Path


class H:
    def __init__(self, name, lights="warm"):
        self.r = {"shape": "custom", "name": name, "lights": lights, "parts": []}

    def p(self, t, x, y, z, w, h, d, c, g=0.0, win=False, r=0.0):
        self.r["parts"].append({"t": t, "p": [round(x, 3), round(y, 3), round(z, 3)], "s": [round(w, 3), round(h, 3), round(d, 3)],
                                "c": c, "g": g, "r": r, "w": win})
        return y + h


def treehouse():
    """#3 @ianna_zab: квадратный домик на яблоне, открытый балкончик с гирляндой, люк и верёвочная лестница,
    круглые окна, фасад из досок, серая металлическая крыша."""
    h = H("Домик на яблоне", "warm")
    wood, dark, plank = "#c8925a", "#7a5030", "#8a5a2f"
    # яблоня: ствол, ветки, крона позади и по бокам, яблоки
    h.p("cyl", 0, 0, -.05, .17, .78, .17, "#5d3b22")
    h.p("cyl", .2, .55, -.12, .06, .3, .06, "#5d3b22")
    h.p("cyl", -.22, .5, -.1, .06, .32, .06, "#5d3b22")
    for x, y, z, s in ((0, 1.08, -.22, .95), (-.33, .86, -.1, .5), (.34, .9, -.12, .5), (-.2, 1.3, .02, .5), (.22, 1.32, .0, .48)):
        h.p("sphere", x, y, z, s, s * .62, s * .72, "#2f9a55", .08)
    for x, y, z in ((-.38, 1.0, .1), (.38, 1.05, .08), (-.1, 1.48, .18), (.18, 1.45, .2), (-.42, .95, -.25), (.28, 1.6, -.05)):
        h.p("sphere", x, y, z, .07, .07, .07, "#e8343a", .35)
    # площадка и дом из досок
    h.p("box", 0, .76, .02, .62, .04, .62, dark)
    h.p("box", 0, .8, -.04, .42, .36, .42, wood)
    for i in range(4):  # доски на фасаде
        h.p("box", 0, .86 + i * .075, .175, .43, .012, .012, plank)
    for i in range(3):
        h.p("box", .215, .86 + i * .1, -.04, .012, .012, .43, plank)
    # круглые окна (светятся)
    for x in (-.11, .11):
        h.p("sphere", x, .93, .178, .1, .1, .025, "#ffd27a", .9)
    h.p("sphere", .218, .93, -.04, .025, .1, .1, "#ffd27a", .9)
    h.p("box", 0, .8, .177, .1, .17, .015, "#4a2c17")  # дверь на балкон
    # серая металлическая крыша
    h.p("pyramid", 0, 1.16, -.04, .58, .24, .58, "#8e949e")
    h.p("box", 0, 1.16, -.04, .5, .02, .5, "#6f757e")
    # открытый балкончик спереди: пол, столбики, перила, гирлянда
    h.p("box", 0, .76, .38, .5, .04, .2, dark)
    for x in (-.24, .24):
        h.p("box", x, .8, .47, .02, .14, .02, plank)
    h.p("box", 0, .93, .47, .5, .02, .025, plank)
    cols = ["#ff3d7f", "#ffd23f", "#5ef2ff", "#a6ff8f", "#c084fc"]
    for i in range(7):
        h.p("sphere", -.21 + i * .07, .9 - (.02 if i % 2 else 0), .48, .035, .035, .035, cols[i % 5], 1)
    # люк снизу и верёвочная лестница
    h.p("box", -.14, .735, -.02, .14, .025, .14, "#3a2416")
    for x in (-.19, -.09):
        h.p("cyl", x, 0, .0, .015, .74, .015, "#d8c39a")
    for i in range(5):
        h.p("box", -.14, .1 + i * .13, .0, .11, .015, .02, "#c9a46a")
    return h.r


def lambo_house():
    """#4 @rost1k_official: дом-машина «Ламборгини» — низкий клиновидный суперкар-дом с подсветкой."""
    h = H("Дом-Ламборгини", "cool")
    body, black, glass = "#ffd21a", "#14141c", "#1d3a7a"
    # колёса (диски-шайбы по бокам) и светящиеся диски
    for x in (-.3, .3):
        for z in (-.25, .25):
            h.p("sphere", x, 0, z, .22, .22, .08, black)
            h.p("sphere", x, .05, z + (.03 if z > 0 else -.03), .11, .11, .03, "#c0c6d4", .5)
    h.p("box", 0, .005, 0, .86, .01, .44, "#b44dff", 1)  # неоновая подсветка днища
    # кузов: низкий корпус-дом с окнами, клиновидный нос, кабина-стекло
    h.p("box", -.06, .07, 0, .76, .15, .48, body, .12, win=True)
    h.p("box", .39, .07, 0, .2, .09, .46, body, .12)
    h.p("box", .47, .07, 0, .06, .05, .44, "#e6b000")
    h.p("pyramid", -.04, .22, 0, .62, .17, .42, glass, .35)
    h.p("box", -.04, .22, 0, .5, .02, .44, body)
    # воздухозаборники, фары, стопы
    for z in (-.245, .245):
        h.p("box", -.12, .1, z, .2, .07, .01, black)
    for z in (-.17, .17):
        h.p("box", .5, .12, z, .01, .03, .1, "#ffffff", 1)
        h.p("box", -.45, .14, z, .01, .03, .12, "#ff2a2a", 1)
    # антикрыло
    for z in (-.15, .15):
        h.p("box", -.41, .22, z, .04, .1, .03, black)
    h.p("box", -.42, .32, 0, .14, .025, .5, body)
    # дверь-«ножницы» (вход в дом) и номер-табличка
    h.p("box", .08, .09, .245, .16, .12, .01, "#e0ac00")
    h.p("box", .08, .09, .25, .015, .12, .005, black)
    h.p("box", .495, .08, 0, .01, .04, .12, "#ffffff", .6)
    return h.r


